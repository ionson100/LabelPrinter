using System.Threading;
using System.Threading.Tasks;

namespace LabelPrinter.Core.Abstractions
{
    /// <summary>
    /// Источник кодов для печати — единственное, что библиотека берёт «снаружи».
    ///
    /// Библиотека ничего не знает про PostgreSQL и Redis: она умеет только
    /// обеспечивать принтер следующим кодом и следить за темпом печати.
    /// Хранилище, откуда берутся коды, полностью на стороне приложения —
    /// это может быть база, файл, очередь сообщений или генератор на лету.
    ///
    /// Буфер тоже живёт в реализации: библиотека лишь задаёт policy
    /// (долить, когда остаток опустился ниже порога), а решение о том,
    /// где хранить очередь — ваше.
    ///
    /// Реализация должна быть безопасна при параллельном вызове из нескольких
    /// принтеров: методы могут выполняться одновременно для разных принтеров.
    /// </summary>
    public interface ICodeSource
    {
        /// <summary>
        /// Сколько кодов сейчас в буфере источника.
        /// Возвращать точное значение не обязательно — движок использует его
        /// только для показателей.
        /// </summary>
        Task<int> GetBufferCountAsync(CancellationToken cancellationToken);

        /// <summary>
        /// Долить буфер, если в нём не больше threshold кодов, до вместимости capacity.
        /// Возвращает, сколько кодов добавлено.
        ///
        /// Если свободных кодов больше нет, реализация обязана вернуть 0 без
        /// исключения: движок сам остановит печать и напишет в журнал.
        /// </summary>
        Task<int> EnsureBufferAsync(int capacity, int threshold, CancellationToken cancellationToken);

        /// <summary>
        /// Забрать один код на печать.
        /// Возвращает null, если кодов больше нет — это штатная ситуация,
        /// а не ошибка: движок остановит печать и сообщит причину.
        /// </summary>
        Task<string> TakeAsync(CancellationToken cancellationToken);

        /// <summary>
        /// Сколько кодов осталось в хранилище, помимо буфера.
        /// Только для показателей: буфер 0, свободно 5000.
        /// </summary>
        Task<long> GetRemainingAsync(CancellationToken cancellationToken);

        /// <summary>Очистить буфер источника. Основное хранилище не трогать.</summary>
        Task ClearAsync(CancellationToken cancellationToken);
    }
}